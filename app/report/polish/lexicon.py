#: 极性词。同条证据正负都命中时两边各计一次，并单独记入 `both`。
POSITIVE_WORDS: tuple[str, ...] = (
    "好用", "很好", "不错", "喜欢", "推荐", "强大", "惊艳", "满意", "香", "方便",
    "免费", "流畅", "准确", "靠谱", "神器", "efficient", "great", "love", "best",
)
NEGATIVE_WORDS: tuple[str, ...] = (
    "难用", "垃圾", "失望", "吐槽", "差评", "不行", "拉胯", "离谱", "胡说", "幻觉",
    "瞎编", "卡顿", "闪退", "崩", "广告", "泄露", "退款", "坑", "bug", "bad", "worst",
)


def hit_topics(text: str) -> list[str]:
    """文本命中的主题名，按 `TOPIC_LEXICON` 声明序返回（结果与输入顺序无关）。"""
    return [topic for topic, words in TOPIC_LEXICON.items() if any(w in text for w in words)]


def hit_polarity(text: str) -> tuple[bool, bool]:
    """(命中正向词, 命中负向词)；两者可同时为真。"""
    return (any(w in text for w in POSITIVE_WORDS), any(w in text for w in NEGATIVE_WORDS))
